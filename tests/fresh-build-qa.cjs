// Reproduce a hosting checkout without ignored, generated folders.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const artifacts = path.join(root, 'artifacts');
fs.mkdirSync(artifacts, { recursive: true });
const fixture = fs.mkdtempSync(path.join(artifacts, 'fresh-build-'));
try {
  for (const dir of ['src', 'scripts', 'assets'])
    fs.cpSync(path.join(root, dir), path.join(fixture, dir), { recursive: true });
  fs.copyFileSync(
    path.join(root, 'Roshan-Industries-Product-Catalogue.xlsx'),
    path.join(fixture, 'Roshan-Industries-Product-Catalogue.xlsx'),
  );
  for (const dir of ['products', 'categories', 'dist'])
    assert(!fs.existsSync(path.join(fixture, dir)));
  const run = (script) =>
    execFileSync(process.execPath, [path.join(fixture, script)], {
      cwd: fixture,
      encoding: 'utf8',
      stdio: 'pipe',
    });
  run('scripts/build.mjs');
  console.log(run('scripts/check.mjs').trim());
  // Rebuilding also removes retired generated routes and recreates dist safely.
  for (const dir of ['products', 'categories'])
    fs.writeFileSync(
      path.join(fixture, dir, 'retired-qa.html'),
      '<!-- Generated by scripts/build.mjs -->',
    );
  run('scripts/build.mjs');
  for (const dir of ['products', 'categories'])
    assert(!fs.existsSync(path.join(fixture, dir, 'retired-qa.html')));
  console.log(run('scripts/check.mjs').trim());
  console.log(
    'PASS: fresh checkout build, repeat build, obsolete route cleanup and hosting output.',
  );
} finally {
  const resolved = fs.realpathSync(fixture);
  assert(path.dirname(resolved) === fs.realpathSync(artifacts), 'Unsafe fixture cleanup');
  fs.rmSync(resolved, { recursive: true });
}
